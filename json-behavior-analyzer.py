"""
------------------------------------------------------------------------------
Script Name:   json-behavior-analyzer.py
Description:   Parses the call-trace JSON produced by `r2-call-tracer.py` and
               builds a per-function behavioural matrix. APIs are mapped to
               high-level capability buckets (file, network, process, crypto,
               injection, anti-analysis, ...) so analysts can spot likely
               droppers, ransomware, injectors and similar patterns at a
               glance.

               v2.0 changes:
                 - Added POSIX coverage (open/read/write/socket/fork/execve/
                   ptrace/mmap/dlopen/...). Previously only Windows APIs
                   were classified, so Linux/macOS samples produced empty
                   reports.
                 - Each bucket now maps to a MITRE ATT&CK technique. Use
                   `--attack-layer FILE.json` to emit an ATT&CK Navigator
                   layer (importable at https://mitre-attack.github.io/
                   attack-navigator/).
                 - Per-function findings can be exported to JSON via
                   `--json` for downstream tooling.

Author:        Generated by Google Gemini, Revised by Ricardo J. Rodríguez
Created:       2025-11-26
Version:       2.0

Requirements:  Standard Python 3 (no pip install needed)
------------------------------------------------------------------------------
"""


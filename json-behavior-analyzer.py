# Colours go to stdout. Strip them when stdout is redirected to a file or
# when NO_COLOR / BINTOPSY_NO_COLOR is set, otherwise downstream tools
# (and the bintopsy-report HTML pipeline) end up with raw escape codes.
_USE_COLOR = (
    sys.stdout.isatty()
    and not os.environ.get("NO_COLOR")
    and not os.environ.get("BINTOPSY_NO_COLOR")
)


def _c(code):
    return code if _USE_COLOR else ""


C_YELLOW  = _c("\033[93m")
C_RED     = _c("\033[91m")
C_MAGENTA = _c("\033[95m")
C_CYAN    = _c("\033[96m")
